#!/usr/bin/env python3
"""Builds gamedata.js (web) and GameData.lua (addon) from data/gamedata.json.

data/gamedata.json is the single source of truth for game rules. Edit it by
hand or with patch_watch.py, then run this script. The tests fail if the
generated files are out of date.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "gamedata.json"
CHANGELOG = ROOT / "data" / "changelog.json"
WEB_OUT = ROOT / "gamedata.js"
LUA_OUT = ROOT / "addon" / "ForeverGuide" / "GameData.lua"

# The addon only needs the rules it calculates with.
LUA_KEYS = ["schema", "updated", "interface", "combat", "auction", "tts", "zones", "dungeons", "startZones", "milestones", "talentTemplates"]

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_LUA_RESERVED = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
                 "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"}


def lua_value(v, indent: int = 0) -> str:
    pad = "    " * (indent + 1)
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "nil"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(v, list):
        if not v:
            return "{}"
        if all(not isinstance(x, (dict, list)) for x in v):
            return "{ " + ", ".join(lua_value(x) for x in v) + " }"
        return "{\n" + "".join(f"{pad}{lua_value(x, indent + 1)},\n" for x in v) + "    " * indent + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for k, x in v.items():
            if isinstance(k, str) and _IDENT.match(k) and k not in _LUA_RESERVED:
                key = k
            elif isinstance(k, str) and k.isdigit():
                key = f'["{k}"]'
            else:
                key = f"[{lua_value(k)}]"
            lines.append(f"{pad}{key} = {lua_value(x, indent + 1)},\n")
        return "{\n" + "".join(lines) + "    " * indent + "}"
    raise TypeError(f"cannot write {type(v)} to Lua")


def render() -> tuple[str, str]:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    changelog = json.loads(CHANGELOG.read_text(encoding="utf-8"))
    web = ("// Generated by companion/build_data.py from data/gamedata.json. Do not edit by hand.\n"
           "(function (root) {\n"
           f"  const data = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
           f"  data.changelog = {json.dumps(changelog, ensure_ascii=False, indent=2)};\n"
           "  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n"
           "  else root.FOREVER_DATA = data;\n"
           "})(typeof window !== \"undefined\" ? window : globalThis);\n")
    subset = {k: data[k] for k in LUA_KEYS if k in data}
    lua = ("-- Generated by companion/build_data.py from data/gamedata.json. Do not edit by hand.\n"
           "local _, FG = ...\n"
           f"FG.Data = {lua_value(subset)}\n")
    return web, lua


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    web, lua = render()
    stale = [p for p, text in ((WEB_OUT, web), (LUA_OUT, lua))
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check:
        for p in stale:
            print(f"Out of date: {p.relative_to(ROOT)}. Run companion/build_data.py.")
        return 1 if stale else 0
    WEB_OUT.write_text(web, encoding="utf-8")
    LUA_OUT.write_text(lua, encoding="utf-8")
    print(f"Wrote {WEB_OUT.relative_to(ROOT)} and {LUA_OUT.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
